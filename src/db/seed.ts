async function seed() {
  console.log('🌱 Seeding DeutschKart default CEFR decks (A1–B2)...');

  for (const deckData of SEED_DECKS) {
    // Upsert deck by slug
    let existingDecks = await db
      .select()
      .from(decks)
      .where(eq(decks.slug, deckData.slug))
      .limit(1);

    let deckId: number;
    if (existingDecks.length > 0) {
      deckId = existingDecks[0].id;
    } else {
      const inserted = await db
        .insert(decks)
        .values({
          slug: deckData.slug,
          title: deckData.title,
          titleDe: deckData.titleDe,
          description: deckData.description,
          level: deckData.level,
          icon: deckData.icon,
          color: deckData.color,
          isSystem: true,
          userId: null,
        })
        .returning({ id: decks.id });
      deckId = inserted[0].id;
    }

    for (let i = 0; i < deckData.words.length; i++) {
      const w = deckData.words[i];
      const normalized = w.word.trim().toLowerCase();

      let existingWord = await db
        .select({ id: globalWords.id })
        .from(globalWords)
        .where(eq(globalWords.normalizedWord, normalized))
        .limit(1);

      let wordId: number;
      if (existingWord.length > 0) {
        wordId = existingWord[0].id;
      } else {
        const insertedWord = await db
          .insert(globalWords)
          .values({
            normalizedWord: normalized,
            word: w.word,
            article: w.article,
            plural: w.plural,
            partOfSpeech: w.partOfSpeech,
            verbForms: w.verbForms,
            persianMeaning: w.persianMeaning,
            englishMeaning: w.englishMeaning,
            exampleDe: w.exampleDe,
            exampleFa: w.exampleFa,
            level: w.level,
          })
          .returning({ id: globalWords.id });
        wordId = insertedWord[0].id;
      }

      await db
        .insert(deckCards)
        .values({
          deckId,
          wordId,
          position: i,
        })
        .onConflictDoNothing();
    }

    console.log(`   ✅ ${deckData.level} · ${deckData.title} (${deckData.words.length} words)`);
  }

  console.log('\n🎉 Seeding complete!');
}

seed()
  .then(() => process.exit(0))
  .catch((err) => {
    console.error('❌ Seed failed:', err);
    process.exit(1);
  });
